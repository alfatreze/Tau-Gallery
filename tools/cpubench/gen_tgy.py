#!/usr/bin/env python3
"""Writes tgydata.h for tools/cpubench/bench4.c: two real 128 x 128 4:2:0 tiles of the frozen conformance vectors (a dense one and a sparse one) as symbol-layer streams, the quantisation tables (JPEG standard at quality 90),
and the checksum of the RGB the Python reconstruction gives for each, so the benchmark also checks its own output on the target."""
import base64, json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/gallery")); sys.path.insert(0, str(ROOT / "sim"))
import numpy as np, tgy_container as C, tgy_encode as E, tgy_recon as R, make_tgy_v0_vectors as G
v = {x["name"]: x for x in json.loads((ROOT / "docs/conformance/tgy_v0_vectors.json").read_text())["vectors"]}
qy, qc = E.scaled_table(E.STD_LUMA, 90), E.scaled_table(E.STD_CHROMA, 90); out = ["/* generated by gen_tgy.py */", "static const unsigned short QY[64] = {%s};" % ",".join(map(str, qy)), "static const unsigned short QC[64] = {%s};" % ",".join(map(str, qc))]
names = ["real_c6227db76b6e", "real_21bda4d32df4"]
def cs(rgb):
    c = 0
    for i, b in enumerate(rgb.reshape(-1).tolist()): c = (c * 31 + b + i) & 0xFFFFFFFF
    return c
for n, name in enumerate(names):
    shapes = [tuple(s) for s in v[name]["shapes"]]; grids = G.unpack(v[name]["blocks"], shapes); stream = bytes.fromhex(v[name]["stream"])
    pic = C.blank_picture(128, 128, C.SUB_420, [qy, qc]); R.assemble(pic, [(0, 0, grids, shapes)]); rgb = R.decode_pixels_tgy(pic)
    out.append("#define TILE%d_LEN %d\n#define TILE%d_CS %du\nstatic const unsigned char tile%d[] = {%s};" % (n, len(stream), n, cs(rgb), n, ",".join(map(str, stream))))
    print(name, "stream bytes", len(stream), "blocks", sum(r * c for r, c in shapes))
Path(__file__).with_name("tgydata.h").write_text("\n".join(out) + "\n")
