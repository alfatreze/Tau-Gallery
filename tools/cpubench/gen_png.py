#!/usr/bin/env python3
"""Writes pngdata.h for tools/cpubench: three 128 x 128 RGB crops as PNG IDAT streams (a detailed photo crop, a smooth sky crop, a synthetic screenshot-like crop), with the raw pixel checksum, so
bench3.c can inflate them on the real core and check the result. Usage: gen_png.py [PHOTO.jpg]"""
import io, struct, sys, zlib
from pathlib import Path
from PIL import Image, ImageDraw
ROOT = Path(__file__).resolve().parents[3]
photo = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "test-images/unsplash/unsplash-1441974231531-c6227db76b6e.jpg"
def idat_of(im):
    b = io.BytesIO(); im.save(b, "PNG", compress_level=6); d = b.getvalue(); pos = 8; idat = b""; ihdr = None
    while pos < len(d):
        n, t = struct.unpack(">I4s", d[pos:pos + 8]); body = d[pos + 8:pos + 8 + n]
        if t == b"IDAT": idat += body
        pos += 12 + n
    return idat
def filters(im):
    raw = zlib.decompress(idat_of(im)); stride = im.width * 3 + 1; h = {}
    for y in range(im.height): h[raw[y * stride]] = h.get(raw[y * stride], 0) + 1
    return h
def cs(raw):
    c = 0
    for i, v in enumerate(raw): c = (c * 31 + v + i) & 0xFFFFFFFF
    return c
src = Image.open(photo).convert("RGB"); W, H = src.size
crops = [("photo", src.crop((W // 2 - 64, H // 2 - 64, W // 2 + 64, H // 2 + 64))), ("sky", src.crop((W // 2 - 64, 20, W // 2 + 64, 148)))]
ui = Image.new("RGB", (128, 128), (30, 30, 36)); d = ImageDraw.Draw(ui)
for i in range(0, 128, 16): d.rectangle((4, i + 2, 120, i + 12), fill=(60 + i, 80, 120)); d.text((8, i + 2), "Tau Gallery %d" % i, fill=(240, 240, 240))
crops.append(("screenshot", ui))
out = ["/* generated by gen_png.py */"]
for n, (name, im) in enumerate(crops):
    idat = idat_of(im); raw = im.tobytes(); z = idat[2:-4]                            # strip the zlib header and the adler32
    out.append(f"#define PNG{n}_NAME \"{name}\"\n#define PNG{n}_W {im.width}\n#define PNG{n}_H {im.height}\n#define PNG{n}_CS {cs(raw)}u\n#define PNG{n}_LEN {len(z)}\nstatic const unsigned char png{n}_data[] = {{" + ",".join(map(str, z)) + "};")
    print(name, "IDAT", len(idat), "bytes, raw", len(raw), "ratio %.2f" % (len(raw) / len(idat)), "filters", filters(im))
out.append("#define PNG_COUNT %d" % len(crops))
Path(__file__).with_name("pngdata.h").write_text("\n".join(out) + "\n")
